func TestIntakeValidation(t *testing.T) {
	for _, tc := range []struct {
		scope      store.Scope
		origin     store.Origin
		text, prov string
		want       error
	}{
		{"project", "robot", "t", "s", ErrBadOrigin},
		{"project", "user", "t", "  ", ErrNoProvenance},
		{"project", "user", "   ", "s", ErrRefused},
	} {
		if _, err := Intake(tc.scope, tc.origin, tc.text, "", tc.prov); !errors.Is(err, tc.want) {
			t.Fatalf("Intake(%q,%q,%q,%q) = %v, want %v", tc.scope, tc.origin, tc.text, tc.prov, err, tc.want)
		}
	}
}

func TestIntakeCapsTextAndQuote(t *testing.T) {
	long := strings.Repeat("wordsx ", MaxTextLen) // both cuts land mid-word, so no space is trimmed
	res, err := Intake("project", store.OriginUser, long, long, "s1")
	if err != nil {
		t.Fatal(err)
	}
	if n := utf8.RuneCountInString(res.Memory.Text); n != MaxTextLen {
		t.Fatalf("text len = %d", n)
	}
	if n := utf8.RuneCountInString(res.Memory.Quote); n != MaxQuoteLen {
		t.Fatalf("quote len = %d", n)
	}
}

func TestSimilar(t *testing.T) {
	for _, tc := range []struct {
		a, b string
		want bool
	}{
		{"make golden regenerates the UI golden files", "Make golden regenerates the UI golden files.", true},
		{"make golden regenerates the UI golden files", "the ui golden files are regenerated by make golden", true},
		{"make golden regenerates the UI golden files", "make check runs vet, tests and gofmt", false},
		{"the user wants short replies", "the user wants commits without being asked", false},
		{"a b c", "A b c", true},
		{"a b c", "a b d", false}, // no content tokens
		{"the dev server listens on port 3000", "the api server listens on port 8080", false},
		{"go test ./internal/... needs CGO_ENABLED=0", "go vet ./internal/... needs CGO_ENABLED=0", false},
	} {
		if got := Similar(tc.a, tc.b); got != tc.want {
			t.Errorf("Similar(%q, %q) = %v", tc.a, tc.b, got)
		}
	}
}

func TestScrubKnownShapes(t *testing.T) {
	// secret is what must not survive; "" means the line must come back untouched
	cases := []struct{ in, secret string }{
		{"key AKIAIOSFODNN7EXAMPLE in aws", "AKIA"},
		{"openai sk-proj-abcdefghij0123456789 done", "sk-proj"},
		{"recurs sk-aaaaaaaaaaaaaaaaaaaa glued xsk-aaaaaaaaaaaaaaaaaaaa", "sk-a"},
		{"github ghp_0123456789abcdefghij012345 end", "ghp_"},
		{"slack xoxb-123456789012-abcd done", "xoxb"},
		{"jwt eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.SflKxwRJSMeKKF2QT4fwpMeJf36POk6yJV_adQssw5c end", "eyJ"},
		{"sha 0123456789abcdef0123456789abcdef01234567 end", "0123456789abcdef"},
		{"blob abcdefghijklmnopqrstuvwxyz0123456789ABCDEFGHIJK end", "abcdefghijklmnopqrstuvwxyz"},
		{"db is postgres://admin:hunter2secret@db.internal:5432/app", "hunter2"},
		{"redis redis://:hunter2@cache:6379 and mysql://u:p@ss@h/db", "hunter2"},
		{"mysql://u:p@ss@h/db", "p@ss"},
		{"see https://x:pw@example.com/a", ":pw@"},
		{`curl -H "Authorization: Bearer abc123def456" https://api.example.com`, "abc123def456"},
		{`curl -H "Authorization: Bearer $API_TOKEN" https://api.example.com`, ""},
		{`psql "password=$DB_PASSWORD host=localhost"`, ""},
		{"export API_KEY=${OPENAI_API_KEY}", ""},
		{"set token: {{deploy_token}} in the template", ""},
		{"see https://example.com:8080/a@b", ""},
		{"clone git@github.com:org/repo.git", ""},
		{"https://user@host/x", ""},
	}
	for _, tc := range cases {
		out, scrubbed := ScrubSecrets(tc.in)
		switch {
		case tc.secret == "" && scrubbed:
			t.Errorf("%q scrubbed to %q", tc.in, out)
		case tc.secret == "":
		case !scrubbed || !strings.Contains(out, "[redacted"):
			t.Errorf("%q: not scrubbed: %q", tc.in, out)
		case strings.Contains(out, tc.secret):
			t.Errorf("%q: secret survived: %q", tc.in, out)
		}
	}
}

func TestScrubEntropyPass(t *testing.T) {
	tok := "Zx9pQ2rTv7Km4Bn8Ld0sWq5Yh" // mixed-case alnum, high entropy, no known prefix
	out, scrubbed := ScrubSecrets("value " + tok + " stays")
	if !scrubbed || strings.Contains(out, tok) {
		t.Fatalf("entropy token survived: %q", out)
	}
	for _, keep := range []string{
		"plain english sentence with common words",
		"config lives in internal/hostapi/permissions_generated_dump_reader.go today",
		"see /Users/someone/Code/github/zemi/internal/learn/scrub.go",
	} {
		if out, s := ScrubSecrets(keep); s {
			t.Fatalf("scrubbed: %q", out)
		}
	}
	b64 := "aGVsbG8/d29ybGQ+Zm9vYmFy/YmF6cXV4K3Rlc3Q9PWxvbmdlcg/QmFzZTY0"
	if out, s := ScrubSecrets("key " + b64 + " end"); !s || strings.Contains(out, b64[:12]) {
		t.Fatalf("base64 with slashes survived: %q", out)
	}
}

